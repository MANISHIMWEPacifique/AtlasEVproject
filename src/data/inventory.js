export function getCarBySlug(slug, cars) {
  return (cars || SEED_INVENTORY).find(c => c.slug === slug);
}

export function getRelatedCars(currentSlug, cars, limit = 3) {
  return (cars || SEED_INVENTORY)
    .filter(c => c.slug !== currentSlug)
    .slice(0, limit);
}
